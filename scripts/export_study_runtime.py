#!/usr/bin/env python3
"""One-way export of the SCE study from the research repo to a runtime studies root.

The SCE study's only maintained source lives in this repository under
``studies/sce_inflation_expectations/``. The SocioVerse2 skill workflow
(``/sv-*``) discovers studies via ``<repo>/studies/*/study.yaml`` and registers
providers via ``import studies.<study_id>``, so running the study through the
official clone requires a copy under that clone's ``studies/``. This script
creates that copy as a *runtime export*: the clone never becomes a second
maintained source.

Usage (from anywhere; paths are resolved from this file):

    python scripts/export_study_runtime.py              # export
    python scripts/export_study_runtime.py --verify     # check the copy
    python scripts/export_study_runtime.py --target-root /path/to/studies

Guarantees:

- The target directory is replaced only if it was created by this exporter
  (marker: ``RUNTIME_EXPORT.json`` with a matching ``exporter`` field) or does
  not exist. Anything else is left untouched and the script exits non-zero.
- Derived/volatile content is not exported: ``__pycache__``/``.DS_Store``,
  ``runs/``, ``versions/`` + ``versions.json``, ``trajectory/`` and
  ``reports/generated/`` contents, ``*.duckdb``. Placeholder READMEs are kept.
- A root ``__init__.py`` is added to the copy when the source has none, so
  ``import studies.<study_id>`` works in the official clone.
- ``RUNTIME_EXPORT.json`` records the export time, the source git HEAD and
  dirty state, and the SHA-256 of every exported file. ``--verify`` recomputes
  the copy's hashes and fails on missing, altered or extra files, so edits made
  in the runtime copy are detected instead of silently diverging.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
STUDY_ID = "sce_inflation_expectations"
SOURCE_DIR = REPO_ROOT / "studies" / STUDY_ID
DEFAULT_TARGET_ROOT = REPO_ROOT.parent / "socioverse2_repo" / "studies"
MANIFEST_NAME = "RUNTIME_EXPORT.json"
EXPORTER_TAG = "socioverse_challenge/scripts/export_study_runtime.py v1"

# Directory/file rules mirroring the repo .gitignore's source-vs-derived split:
# these never belong in a runtime export.
EXCLUDED_DIR_NAMES = {"__pycache__", "runs", "versions"}
# Subtrees whose *contents* are derived, but whose placeholder READMEs travel.
PRUNED_CONTENT_DIRS = {"trajectory", "reports"}
EXCLUDED_FILE_NAMES = {".DS_Store", "versions.json"}
EXCLUDED_SUFFIXES = {".duckdb", ".pyc"}

INIT_FALLBACK = (
    '"""Runtime export marker package for the SCE study.\n\n'
    "Generated by socioverse_challenge/scripts/export_study_runtime.py because\n"
    "the source study has no __init__.py. Do not edit in the runtime copy.\n"
    '"""\n'
)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _git_state() -> dict:
    def run(*args: str) -> str:
        try:
            return subprocess.run(
                ["git", "-C", str(REPO_ROOT), *args],
                capture_output=True, text=True, check=True,
            ).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            return ""

    head = run("rev-parse", "HEAD")
    dirty = run("status", "--porcelain", "--", f"studies/{STUDY_ID}")
    tracked = bool(run("ls-files", "--", f"studies/{STUDY_ID}"))
    return {
        "source_git_head": head or None,
        "source_tracked_in_git": tracked,
        "source_dirty_or_untracked": bool(dirty) or not tracked,
    }


def _iter_export_files(source: Path) -> list[Path]:
    """Source files that belong in the runtime copy, sorted for stability."""
    files: list[Path] = []
    for path in source.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(source)
        parts = rel.parts
        if any(part in EXCLUDED_DIR_NAMES for part in parts):
            continue
        # trajectory/ and reports/ keep only their top-level README placeholders.
        if parts[0] in PRUNED_CONTENT_DIRS and rel.name != "README.md":
            continue
        if rel.name in EXCLUDED_FILE_NAMES or path.suffix in EXCLUDED_SUFFIXES:
            continue
        files.append(path)
    return sorted(files)


def _build_manifest(files: list[Path], source: Path, target: Path) -> dict:
    return {
        "exporter": EXPORTER_TAG,
        "study_id": STUDY_ID,
        "exported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source_dir": str(source),
        "target_dir": str(target),
        "direction": "one-way: edit the source repo, re-export; never edit the copy",
        **_git_state(),
        "file_count": len(files),
        "files": {
            str(p.relative_to(source)).replace("\\", "/"): _sha256(p) for p in files
        },
    }


def export(target_root: Path) -> Path:
    if not (SOURCE_DIR / "study.yaml").is_file():
        sys.exit(f"source study not found or missing study.yaml: {SOURCE_DIR}")
    target = target_root / STUDY_ID
    manifest_path = target / MANIFEST_NAME
    if target.exists():
        try:
            marker = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            marker = {}
        if marker.get("exporter") != EXPORTER_TAG:
            sys.exit(
                f"{target} exists and was not created by this exporter; "
                "refusing to overwrite. Move it away or export elsewhere."
            )
        shutil.rmtree(target)
    target.mkdir(parents=True)

    files = _iter_export_files(SOURCE_DIR)
    for src in files:
        dst = target / src.relative_to(SOURCE_DIR)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
    if not (target / "__init__.py").exists():
        (target / "__init__.py").write_text(INIT_FALLBACK, encoding="utf-8")

    manifest = _build_manifest(files, SOURCE_DIR, target)
    if "__init__.py" not in manifest["files"]:
        manifest["files"]["__init__.py"] = _sha256(target / "__init__.py")
        manifest["file_count"] += 1
        manifest["generated_files"] = ["__init__.py"]
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"exported {manifest['file_count']} files -> {target}")
    print(f"manifest: {manifest_path}")
    if manifest["source_dirty_or_untracked"]:
        print("note: source study is dirty/untracked in git; hashes in the manifest "
              "are the export-time truth")
    return target


def verify(target_root: Path) -> int:
    target = target_root / STUDY_ID
    manifest_path = target / MANIFEST_NAME
    if not manifest_path.is_file():
        print(f"no export manifest at {manifest_path}; nothing to verify")
        return 1
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    recorded: dict[str, str] = manifest.get("files", {})
    problems: list[str] = []
    for rel, expected in recorded.items():
        path = target / rel
        if not path.is_file():
            problems.append(f"missing: {rel}")
        elif _sha256(path) != expected:
            problems.append(f"altered: {rel}")
    extras = [
        str(p.relative_to(target))
        for p in target.rglob("*")
        if p.is_file()
        and p.name != MANIFEST_NAME
        and str(p.relative_to(target)) not in recorded
    ]
    problems.extend(f"extra: {rel}" for rel in sorted(extras))
    if problems:
        print(f"verify FAILED for {target} ({len(problems)} problem(s)):")
        for line in problems:
            print(f"  {line}")
        print("the runtime copy diverged from the recorded export; re-export from "
              "the source repo instead of editing the copy")
        return 1
    print(f"verify OK: {target} matches {manifest_path.name} "
          f"({manifest.get('file_count')} files, exported {manifest.get('exported_at')})")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--target-root", type=Path, default=DEFAULT_TARGET_ROOT,
                    help=f"runtime studies root (default: {DEFAULT_TARGET_ROOT})")
    ap.add_argument("--verify", action="store_true",
                    help="check the exported copy against its manifest; do not write")
    args = ap.parse_args(argv)
    if args.verify:
        return verify(args.target_root)
    export(args.target_root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
